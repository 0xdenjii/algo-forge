# LeetCode 72 - Edit Distance
# Problem: Minimum insert/delete/replace operations to turn word1 into
#   word2.
# Approach: Classic Levenshtein DP keeping only one previous row.
# Time: O(n * m)  Space: O(m)


def min_distance(a: str, b: str) -> int:
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i] + [0] * len(b)
        for j, cb in enumerate(b, 1):
            cur[j] = prev[j - 1] if ca == cb else 1 + min(prev[j - 1], prev[j], cur[j - 1])
        prev = cur
    return prev[-1]


if __name__ == "__main__":
    assert min_distance("horse", "ros") == 3
    assert min_distance("intention", "execution") == 5
    assert min_distance("", "abc") == 3
    print("ok")
